#!/usr/bin/env python3
"""Generates every launcher icon and launch image from one design.

The mark is the Material Symbols "local_fire_department" flame (Apache-2.0,
from the Flutter SDK's MaterialIcons font) on the app's gray scale:
near black #212529 with a near white #F8F9FA flame.

Usage: python3 tool/branding/generate_icons.py   (needs Pillow)
Run from the repository root. Outputs are committed; rerun after a change.
"""
import json
import os
import subprocess
from PIL import Image, ImageDraw, ImageFont

DARK = (0x21, 0x25, 0x29, 255)
LIGHT = (0xF8, 0xF9, 0xFA, 255)
GLYPH = chr(0xF86B)


def flutter_font():
    flutter = subprocess.check_output(['which', 'flutter'], text=True).strip()
    root = os.path.dirname(os.path.dirname(os.path.realpath(flutter)))
    return os.path.join(root, 'bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf')


FONT = flutter_font()


def glyph(size, color, scale):
    """The flame centred on a transparent square of `size` px, filling `scale`."""
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    font = ImageFont.truetype(FONT, int(size * scale))
    draw = ImageDraw.Draw(img)
    left, top, right, bottom = draw.textbbox((0, 0), GLYPH, font=font)
    x = (size - (right - left)) / 2 - left
    y = (size - (bottom - top)) / 2 - top
    draw.text((x, y), GLYPH, font=font, fill=color)
    return img


def tile(size, background, foreground, radius_ratio=0.0, scale=0.62):
    """Square icon with optional rounded corners (0 = full bleed)."""
    big = size * 4  # supersample for smooth edges
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle(
        (0, 0, big - 1, big - 1), radius=int(big * radius_ratio), fill=background)
    img.alpha_composite(glyph(big, foreground, scale))
    return img.resize((size, size), Image.LANCZOS)


def save(img, path, opaque=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if opaque:
        img = img.convert('RGB')  # App Store icons must have no alpha
    img.save(path, optimize=True)


def android():
    res = 'android/app/src/main/res'
    densities = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
    for name, d in densities.items():
        # Legacy icons (Android 7 and below never apply here: minSdk 26 uses
        # adaptive icons, but launchers may still read these).
        save(tile(int(48 * d), DARK, LIGHT, radius_ratio=0.22),
             f'{res}/mipmap-{name}/ic_launcher.png')
        save(tile(int(48 * d), DARK, LIGHT, radius_ratio=0.5),
             f'{res}/mipmap-{name}/ic_launcher_round.png')
        # Adaptive icon layers: 108 dp, content inside the 66 dp safe zone.
        fg = glyph(int(108 * d * 4), LIGHT, 0.40).resize(
            (int(108 * d), int(108 * d)), Image.LANCZOS)
        save(fg, f'{res}/mipmap-{name}/ic_launcher_foreground.png')
        mono = glyph(int(108 * d * 4), (0, 0, 0, 255), 0.40).resize(
            (int(108 * d), int(108 * d)), Image.LANCZOS)
        save(mono, f'{res}/mipmap-{name}/ic_launcher_monochrome.png')
        # Android 12+ splash icon: 240 dp canvas, mark inside 160 dp circle.
        splash = Image.new('RGBA', (int(240 * d),) * 2, (0, 0, 0, 0))
        mark = tile(int(112 * d), DARK, LIGHT, radius_ratio=0.24)
        off = (int(240 * d) - mark.width) // 2
        splash.alpha_composite(mark, (off, off))
        save(splash, f'{res}/drawable-{name}/splash_icon.png')
        # Pre-12 launch screen mark.
        save(tile(int(96 * d), DARK, LIGHT, radius_ratio=0.24),
             f'{res}/drawable-{name}/launch_mark.png')
    os.makedirs(f'{res}/mipmap-anydpi-v26', exist_ok=True)
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding/generate_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
'''
    for name in ('ic_launcher', 'ic_launcher_round'):
        with open(f'{res}/mipmap-anydpi-v26/{name}.xml', 'w') as f:
            f.write(adaptive)


def ios():
    base = 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
    with open(f'{base}/Contents.json') as f:
        contents = json.load(f)
    for image in contents['images']:
        points = float(image['size'].split('x')[0])
        scale = int(image['scale'].rstrip('x'))
        px = int(round(points * scale))
        # iOS masks the corners itself: full bleed, opaque.
        save(tile(px, DARK, LIGHT, radius_ratio=0, scale=0.58),
             f"{base}/{image['filename']}", opaque=True)
    launch = 'ios/Runner/Assets.xcassets/LaunchImage.imageset'
    images = []
    for scale in (1, 2, 3):
        suffix = '' if scale == 1 else f'@{scale}x'
        light = tile(96 * scale, DARK, LIGHT, radius_ratio=0.24)
        dark = tile(96 * scale, LIGHT, DARK, radius_ratio=0.24)
        save(light, f'{launch}/LaunchImage{suffix}.png')
        save(dark, f'{launch}/LaunchImageDark{suffix}.png')
        images.append({'idiom': 'universal', 'filename': f'LaunchImage{suffix}.png',
                       'scale': f'{scale}x'})
        images.append({'idiom': 'universal', 'filename': f'LaunchImageDark{suffix}.png',
                       'scale': f'{scale}x',
                       'appearances': [{'appearance': 'luminosity', 'value': 'dark'}]})
    with open(f'{launch}/Contents.json', 'w') as f:
        json.dump({'images': images, 'info': {'version': 1, 'author': 'xcode'}}, f, indent=2)
        f.write('\n')


def store():
    os.makedirs('docs/store/graphics', exist_ok=True)
    save(tile(512, DARK, LIGHT, radius_ratio=0, scale=0.58),
         'docs/store/graphics/play_icon_512.png', opaque=True)
    # Play feature graphic 1024x500: mark and name on the light canvas.
    fg = Image.new('RGBA', (1024, 500), LIGHT)
    fg.alpha_composite(tile(220, DARK, LIGHT, radius_ratio=0.24), (110, 140))
    font = ImageFont.truetype('assets/fonts/NotoSans-Bold.ttf', 104)
    ImageDraw.Draw(fg).text((380, 160), 'Emberwit', font=font, fill=DARK)
    small = ImageFont.truetype('assets/fonts/NotoSans-Regular.ttf', 38)
    ImageDraw.Draw(fg).text((384, 300), 'Private AI. Works offline.', font=small,
                            fill=(0x49, 0x50, 0x57, 255))
    save(fg, 'docs/store/graphics/play_feature_1024x500.png', opaque=True)


if __name__ == '__main__':
    android()
    ios()
    store()
    print('icons generated')
